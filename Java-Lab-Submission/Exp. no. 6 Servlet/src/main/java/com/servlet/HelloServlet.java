package com.servlet;

import java.io.IOException;
import java.io.PrintWriter;
import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

@WebServlet("/hello")
public class HelloServlet extends HttpServlet {
    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        response.setContentType("text/html; charset=UTF-8");

        String name = request.getParameter("name");
        if (name == null || name.isBlank()) {
            name = "Students";
        }

        try (PrintWriter out = response.getWriter()) {
            out.println("<!doctype html>");
            out.println("<html><head><meta charset='UTF-8'><title>Hello Servlet</title>");
            out.println("<style>body{font-family:Arial;margin:40px;background:#f4f7fb;color:#172033}"
                    + ".card{max-width:650px;margin:auto;background:white;padding:28px;border-radius:14px;"
                    + "box-shadow:0 4px 18px #0001}h1{color:#155eef}</style></head><body>");
            out.println("<div class='card'><h1>Hello " + escapeHtml(name) + "!</h1>");
            out.println("<p>Welcome to Java Servlet Programming.</p>");
            out.println("<p>This response was generated by <code>HelloServlet</code> using doGet().</p>");
            out.println("<p><a href='index.html'>Back to Home</a></p></div></body></html>");
        }
    }

    private String escapeHtml(String value) {
        return value.replace("&", "&amp;").replace("<", "&lt;")
                    .replace(">", "&gt;").replace("\"", "&quot;")
                    .replace("'", "&#x27;");
    }
}
